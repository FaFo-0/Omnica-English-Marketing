import { session, go } from './browse.mjs';
import { startRec, swipe, tap } from './rec.mjs';
const LESSON = process.argv[2];
const SC = '/tmp/claude-0/-home-user/f8c2bbaa-ba06-5d68-8076-37eff19a0f58/scratchpad/';
const { browser, page } = await session('teacher');
await go(page, `/teacher/sessions/${LESSON}`, 2500);
await page.getByText('Homework', { exact: true }).first().click(); await page.waitForTimeout(1500);
const rec = await startRec(page, '/home/user/sally-ad/screens/s6a_frames');
await page.waitForTimeout(800);
const card = page.locator('div', { has: page.getByText('Correct the mistake', { exact: true }) }).filter({ has: page.getByRole('button', { name: 'Generate with AI' }) }).last();
await tap(page, card.getByRole('button', { name: 'Generate with AI' }), 1200);
rec.mark('form');
await tap(page, page.getByLabel('Fill the gaps').first(), 600);
await tap(page, page.getByRole('button', { name: 'Generate preview' }), 500);
rec.mark('ai_start');
await page.getByRole('button', { name: 'Add to worksheet' }).waitFor({ timeout: 120000 });
rec.mark('ai_done');
await page.getByText('AI draft — review before inserting').scrollIntoViewIfNeeded(); await page.waitForTimeout(1200);
await tap(page, page.getByRole('button', { name: 'Student view' }), 2000);
for (let i = 0; i < 5; i++) { await swipe(page, 300); await page.waitForTimeout(1100); }
await page.screenshot({ path: SC + 's6a_mid.png' });
rec.mark('insert');
await tap(page, page.getByRole('button', { name: 'Add to worksheet' }), 2000);
await page.getByRole('button', { name: /^Approve/ }).first().scrollIntoViewIfNeeded().catch(() => {});
await tap(page, page.getByRole('button', { name: /^Approve/ }).first(), 2500);
rec.mark('end');
await page.screenshot({ path: SC + 's6a_end.png' });
console.log(await rec.stop('/home/user/sally-ad/screens/s6a_teacher_hw.mp4'));
await browser.close();
