import { session, go } from './browse.mjs';
import { startRec, swipe, tap } from './rec.mjs';
const LESSON = process.argv[2];
const { browser, page } = await session('teacher');
await go(page, `/teacher/sessions/${LESSON}`, 2500);
const rec = await startRec(page, '/home/user/sally-ad/screens/s2_frames');
await page.waitForTimeout(1000);
await tap(page, page.getByText('Summary', { exact: true }).first(), 1000);
rec.mark('summary_gen');
await tap(page, page.getByRole('button', { name: 'Regenerate' }).first(), 500);
await page.waitForTimeout(30000);
rec.mark('summary_ready');
await swipe(page, 300); await page.waitForTimeout(1500); await swipe(page, -300); await page.waitForTimeout(800);
await tap(page, page.getByRole('button', { name: 'Approve' }).first(), 1500);
await tap(page, page.getByText('Vocabulary', { exact: true }).first(), 1000);
rec.mark('vocab_gen');
await tap(page, page.getByRole('button', { name: 'Regenerate' }).first(), 500);
await page.waitForTimeout(45000);
rec.mark('vocab_ready');
await swipe(page, 400); await page.waitForTimeout(1500); await swipe(page, 400); await page.waitForTimeout(1500); await swipe(page, -800, { steps: 36 }); await page.waitForTimeout(800);
await tap(page, page.getByRole('button', { name: 'Approve' }).first(), 1500);
rec.mark('publish');
await tap(page, page.getByRole('button', { name: 'Publish' }).first(), 3000);
rec.mark('end');
await page.screenshot({ path: '/tmp/claude-0/-home-user/f8c2bbaa-ba06-5d68-8076-37eff19a0f58/scratchpad/s2_end.png' });
console.log(await rec.stop('/home/user/sally-ad/screens/s2_publish.mp4'));
await browser.close();
